#########################
# Preprocess rare variant borzoi effects (one file per tissue)
#########################
if false; then
tail -n +2 "$borzoi_gtex_unique_target_names_file" | while IFS=$'\t' read -r orig_target_index borzoi_target_index target_sample target_description target_tissue; do
	sbatch preprocess_rare_variant_borzoi_effects.sh $gtex_pc_genes_gtf $rare_variant_borzoi_results_dir $orig_target_index $borzoi_target_index $borzoi_gtex_only_target_names_file $target_tissue $target_sample $rare_variant_borzoi_output_dir
done
fi



#########################
# Rare variant personalized expression correlations (per tissue)
#########################
if false; then
tail -n +2 "$borzoi_gtex_unique_target_names_file" | while IFS=$'\t' read -r orig_target_index borzoi_target_index target_sample target_description target_tissue; do
    rare_variant_borzoi_results_file=${rare_variant_borzoi_output_dir}${target_tissue}"_"${target_sample}"_rare_variant_borzoi_effects.txt.gz"
    common_variant_borzoi_results_file=${common_variant_borzoi_predicted_effect_sizes_directory}${target_tissue}"_"${target_sample}"_borzoi_effects.txt.gz"
    expression_file=${gtex_expression_directory}${target_tissue}".v8.residualized_expression_renormalized.bed"
    plink_genotype_stem=${gtex_genotype_directory}"gtex_v9_eqtl_chr"
    genotype_sample_mapping_file=${gtex_genotype_directory}"genotype_sample_mapping_to_"${target_tissue}"_expression_samples.txt"

    expression_correlation_output_file=${per_tissue_personalized_expression_dir}${target_tissue}"_"${target_sample}"_personalized_expression_prediction.txt"

    sbatch rare_variant_personalized_expression_correlations_per_tissue.sh $sldmc_summary_file $rare_variant_borzoi_results_file $common_variant_borzoi_results_file $expression_file $plink_genotype_stem $genotype_sample_mapping_file $rare_variant_carrier_stem $eur_vcf_sample_list $maf_threshold $expression_correlation_output_file
done
fi



#########################
# Visualize personalized expression correlation results (five tissues; heritable genes and all genes)
#########################
if false; then
source ~/.bashrc
conda activate plink_env
Rscript visualize_personalized_expression_correlations.R $per_tissue_personalized_expression_dir $borzoi_gtex_unique_target_names_file $visualize_personalized_expression_dir
fi