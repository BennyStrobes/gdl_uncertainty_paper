#########################
# Input data
#########################

sldmc_summary_file="/lab-share/CHIP-Strober-e2/Public/ben/gdl_uncertainty_paper/sldmc_analysis/sldmc_results/sldmc_results_cross_tissue_meta_analyzed_default_bootstrap_stats.txt"

# Following directory contains expression files per tissue like: Whole_Blood.v8.residualized_expression_renormalized.bed
gtex_expression_directory="/lab-share/CHIP-Strober-e2/Public/ben/gdl_uncertainty_paper/gtex_eqtl_expression_processing/residualized_expression/"

# Following contains (common variant) genotype data
# Chrom specific plink files: gtex_v9_eqtl_chr10.bed
# And then file containing sample indices: genotype_sample_mapping_to_Whole_Blood_expression_samples.txt
# (Only used to get the per-bin mean genotype variance of the S-LDMC variant set for the allele-frequency-specific residual variance)
gtex_genotype_directory="/lab-share/CHIP-Strober-e2/Public/ben/gdl_uncertainty_paper/gtex_eqtl_expression_processing/plink_processed_genotype/"

# Following directory contains Borzoi predicted (common variant) effect sizes
# Contains one file for each tissue like: "Whole_Blood_GTEX-1LB8K-0005-SM-DIPED.1_borzoi_effects.txt.gz"
common_variant_borzoi_predicted_effect_sizes_directory="/lab-share/CHIP-Strober-e2/Public/ben/gdl_uncertainty_paper/sldmc_analysis/processed_borzoi/"

# Directory containing results of borzoi runs on rare variants (Justin)
# Same h5 format as the genome-wide run: variants_chunk_00.borzoi_output.h5, ...
rare_variant_borzoi_results_dir="/lab-share/CHIP-Strober-e2/Public/Justin_Li/borzoi_outputs/all_20_chunks/"

# Directory containing results of (common variant) borzoi runs
borzoi_results_dir="/lab-share/CHIP-Strober-e2/Public/ben/borzoi_genome_wide_run/genome_wide/borzoi_predictions/"

# Directory containing borzoi gtex target indices and names
borzoi_gtex_unique_target_names_file=${borzoi_results_dir}"targets_gtex_v8_eqtl_only_unique_ordered.txt"
# All gtex targets (used to tell whether the rare variant h5 files contain all borzoi targets or gtex targets only)
borzoi_gtex_only_target_names_file=${borzoi_results_dir}"targets_gtex_only_ordered.txt"

# Gtex protein coding genes
gtex_pc_genes_gtf="/lab-share/CHIP-Strober-e2/Public/gene_annotation_files/gencode.v39.gtex.protein_coding.genes.gtf"

# Rare variant directory (generated by rare_variant_s2e/process_rare_variants)
# Contains chrom specific carrier tables like: gtex.eur.pass.rare_maf_lt_0.0025.snvs.chr1.rare_variant_carriers_near_genes.tsv.gz
rare_variant_dir="/lab-share/CHIP-Strober-e2/Public/ben/rare_variant_s2e/preprocess_rare_variants/"
rare_variant_carrier_stem=${rare_variant_dir}"gtex.eur.pass.rare_maf_lt_0.0025.snvs"
eur_vcf_sample_list=${rare_variant_dir}"european_ancestry_vcf_sample_list.txt"

# Only use rare variants with MAF below this threshold
# (note: carrier tables are already limited to MAF < 0.0025)
maf_threshold="0.01"


#########################
# Output data
#########################
rare_var_expression_correlations_root_directory="/lab-share/CHIP-Strober-e2/Public/ben/gdl_uncertainty_paper/rare_var_expression_correlations/"

rare_variant_borzoi_output_dir=${rare_var_expression_correlations_root_directory}"processed_borzoi/"

per_tissue_personalized_expression_dir=${rare_var_expression_correlations_root_directory}"personalized_expression_per_tissue/"

visualize_personalized_expression_dir=${rare_var_expression_correlations_root_directory}"visualize_personalized_expression/"



#########################
# Code
